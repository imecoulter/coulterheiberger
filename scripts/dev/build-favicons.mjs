#!/usr/bin/env node
/**
 * Produces the site's icon set in `public/`, from one CH monogram set in the
 * committed Montserrat subset.
 *
 * Like `build-social-card.mjs` and `subset-fonts.mjs`, this is a LOCAL dev tool.
 * `.github/workflows/deploy.yml` is Node-only and never runs it; the committed
 * files are what CI ships. No `npm run` alias for the same reason those two have
 * none: a script in package.json reads as part of the build, and this is not.
 *
 * ## Run
 *
 *   PYTHON=.venv-fonts/Scripts/python.exe node scripts/dev/build-favicons.mjs
 *
 * ## What it replaces
 *
 * Astro's own logo. The starter's `favicon.svg` shipped unchanged from the first
 * commit through the whole v1 build, which is the sort of thing that is invisible
 * in a diff and obvious in a tab strip.
 *
 * ## Why four files and not one
 *
 * | file | who reads it |
 * | --- | --- |
 * | `favicon.ico` | browsers request `/favicon.ico` whether it is declared or not |
 * | `favicon.svg` | every modern engine, and the only one that inverts for a dark tab strip |
 * | `icon-192.png` | Google Search, which wants a square multiple of 48 and does not read SVG |
 * | `apple-touch-icon.png` | iOS home screen and bookmark |
 *
 * ## Why the rasters are opaque and the SVG is not
 *
 * The SVG carries a `prefers-color-scheme` swap, so it is transparent and the mark
 * follows the browser's theme. A raster cannot do that, and a transparent
 * near-black mark handed to a dark search results page is an invisible mark. So
 * every PNG and every ICO entry is composited onto the paper ground. That is also
 * what iOS wants: it composites a transparent touch icon onto black.
 *
 * ## Known risk, recorded rather than discovered later
 *
 * TWO LETTERS AT 16px IS THE TIGHT CASE. The monogram is set edge to edge with
 * negative tracking so the strokes are as heavy as the artboard allows, and the
 * counters of C and H are what carry it. If it fills in on a real tab strip, the
 * fix is a different mark rather than a tweak to this file. Judge it rendered, not
 * in the SVG.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';
import { repoRoot } from '../lib/repo.mjs';
import { outline } from '../lib/outline.mjs';

const root = repoRoot();
const OUT = join(root, 'public');
const FONT = join(root, 'src', 'fonts', 'montserrat-wght500-site-trimmed.woff2');

/* Mirrors tokens.css. Stated here rather than parsed because this script emits
   rasters, not CSS, and a generator that reads the stylesheet to decide what
   colour to bake into a PNG is a coupling with no payoff — the icon does not
   re-render when a token changes, it is regenerated by hand.

   NOT pure black and white. The mark is the site's ink, and at these sizes the
   difference from #000 is imperceptible while the difference in principle is
   that the icon is on the palette. */
const INK_DAY = '#14161A';
const INK_NIGHT = '#E8E6E1';
const GROUND = '#F2F0EC';

const TEXT = 'CH';

/** Negative, and further than --track-display's -0.02em. A monogram is not a
    word: the two letters are one mark, and the space between them is the first
    thing that dissolves at 16px. */
const TRACKING = -0.045;

/** The artboard. Arbitrary for a vector, and 512 keeps the emitted path
    transform readable rather than a string of leading zeroes. */
const VIEW = 512;

/** How much of the artboard the ink fills, on its larger axis. Deliberately
    close to the edge: every percent of padding is stroke weight given away at
    the size where this is hardest to read. It is not 1.0 because a mark touching
    the exact edge reads as clipped inside a browser's rounded tab. */
const FILL = 0.88;

// ---- compose ---------------------------------------------------------------

const run = outline(FONT, TEXT, VIEW, TRACKING);

/* Fit the INK bounds, not the advance width. The advance carries the trailing
   sidebearing, so fitting it would leave the mark visibly off-centre to the
   left — which is the classic monogram bug and is invisible until you put the
   icon next to another one. */
const { bounds } = run;
const scale = (VIEW * FILL) / Math.max(bounds.width, bounds.height);

/* Glyph outlines are Y-up in font units, so the transform is a `scale(s, -s)`
   under a translate. The translate puts the ink's centre on the artboard's
   centre: x is a straight offset, y is negated because the axis flipped. */
const cx = VIEW / 2 - (bounds.xMin + bounds.width / 2) * scale;
const cy = VIEW / 2 + (bounds.yMin + bounds.height / 2) * scale;
const transform = `translate(${cx.toFixed(3)} ${cy.toFixed(3)}) scale(${scale.toFixed(6)} ${(-scale).toFixed(6)})`;

/**
 * The delivered SVG. Transparent, with the theme swap in an embedded <style> —
 * the same mechanism the file it replaces used, kept because it is the one thing
 * a vector favicon can do that none of the rasters can.
 */
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW} ${VIEW}">
  <path transform="${transform}" d="${run.d}"/>
  <style>
    path { fill: ${INK_DAY}; }
    @media (prefers-color-scheme: dark) {
      path { fill: ${INK_NIGHT}; }
    }
  </style>
</svg>
`;

/**
 * The rasterisation source. A SEPARATE string, not the file above, for two
 * reasons: librsvg does not evaluate `prefers-color-scheme`, so it would silently
 * bake the day fill anyway, and the rasters need the opaque ground the delivered
 * SVG must not have.
 *
 * `width`/`height` are set per size so librsvg rasterises AT the target rather
 * than rendering once and downscaling. A 512 to 16 downscale is a different and
 * mushier image than a 16px render.
 */
const raster = (size) =>
  Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${VIEW} ${VIEW}">` +
      `<rect width="${VIEW}" height="${VIEW}" fill="${GROUND}"/>` +
      `<path transform="${transform}" d="${run.d}" fill="${INK_DAY}"/>` +
      `</svg>`,
  );

const png = (size) => sharp(raster(size)).png({ compressionLevel: 9 }).toBuffer();

// ---- the ICO container -----------------------------------------------------

/**
 * Written by hand rather than pulled in as a dependency. An ICO is a six-byte
 * header, a sixteen-byte directory entry per image, and the payloads; PNG
 * payloads have been legal since Vista and every browser that still asks for a
 * `.ico` reads them. That is less code than the package that would do it, and
 * this repo already hand-rolls its OKLab round trip for the same reason.
 *
 * The one trap: WIDTH AND HEIGHT ARE SINGLE BYTES, and 256 is encoded as 0.
 * Nothing here goes near 256, but a future 256px entry written as `256 & 0xff`
 * happens to be correct by accident, and as `256` throws. Stated so it is a
 * decision rather than luck.
 *
 * @param {{ size: number, data: Buffer }[]} images
 */
function ico(images) {
  const HEADER = 6;
  const ENTRY = 16;

  const header = Buffer.alloc(HEADER);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // 1 = icon
  header.writeUInt16LE(images.length, 4);

  let offset = HEADER + ENTRY * images.length;
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(ENTRY);
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt8(0, 2); // palette colours, 0 for truecolour
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    return entry;
  });

  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

// ---- emit ------------------------------------------------------------------

mkdirSync(OUT, { recursive: true });

/* 16 and 32 are the tab strip and the bookmark bar. 48 is in the .ico because
   Windows uses it and because it is the size Google Search asks for, which
   costs a few hundred bytes here and removes a reason to wonder later. */
const ICO_SIZES = [16, 32, 48];
const icoImages = await Promise.all(
  ICO_SIZES.map(async (size) => ({ size, data: await png(size) })),
);

/* 180 is Apple's current touch icon size and the only one iOS needs; it
   downscales the rest itself. 192 is Google Search's square-multiple-of-48.
   512 is the largest anything asks for and the one a future manifest would
   use. */
const files = [
  ['favicon.svg', Buffer.from(svg, 'utf8')],
  ['favicon.ico', ico(icoImages)],
  ['apple-touch-icon.png', await png(180)],
  ['icon-192.png', await png(192)],
  ['icon-512.png', await png(512)],
];

for (const [name, data] of files) {
  writeFileSync(join(OUT, name), data);
  console.log(`  ${name.padEnd(22)} ${String(data.length).padStart(6)} B`);
}

console.log(
  `\nfavicons  "${TEXT}"  ink bounds ${bounds.width.toFixed(0)}x${bounds.height.toFixed(0)} font units, ` +
    `fitted to ${(VIEW * FILL).toFixed(0)}/${VIEW}\n` +
    `  Look at favicon.ico at 16px in a real tab strip before trusting it.`,
);
